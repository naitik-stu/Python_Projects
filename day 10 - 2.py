run_calc = True

def add(n1, n2):
    return n1 + n2

def subtract(n1, n2):
    return n1 - n2

def multiply(n1, n2):
    return n1 * n2

def divide(n1, n2):
    return n1 / n2

n01 = int(input("Enter the first number: "))

while run_calc:

    operator = input("Enter the operator (+ - * /): ")
    n02 = int(input("Enter the second number: "))

    if operator == "+":
        calc_run = add
    elif operator == "-":
        calc_run = subtract
    elif operator == "*":
        calc_run = multiply
    elif operator == "/":
        calc_run = divide
    else:
        print("Invalid operator")
        continue

    result = calc_run(n01, n02)
    print(f"{n01} {operator} {n02} = {result}")

    again = input("Type 'y' to continue with this result or 'n' to start over: ")

    if again == "y":
        n01 = result
    else:
        n01 = int(input("Enter the first number: "))
